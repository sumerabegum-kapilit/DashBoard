// Builds client/studio.css from the sources in client/css, with every rule scoped to .ds-root (the element
// mount() creates), so the studio's styles never reach the host page and the host's reach it only where
// they target the studio. Run after changing anything in client/css:  npm run build:css
const fs = require('fs');
const path = require('path');

const SCOPE = '.ds-root';
const DIR = path.join(__dirname, '..', 'client');
const SOURCES = ['css/base.css', 'css/studio.css', 'css/module.css'];

function prefix(selector) {
  return selector.split(',').map((raw) => {
    const s = raw.trim();
    if (!s) return s;
    if (/^(html|body)$/.test(s)) return SCOPE;
    if (s.startsWith(':root')) return SCOPE + s.slice(5);
    if (s.startsWith('body.studio')) return SCOPE + s.slice('body.studio'.length);
    if (s.startsWith('body')) return SCOPE + s.slice(4);
    if (s === '*') return `${SCOPE}, ${SCOPE} *`;
    return `${SCOPE} ${s}`;
  }).join(', ');
}

// Walks the rules, keeping @media and @supports blocks and scoping what is inside them.
function scope(css) {
  let out = '';
  let i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i);
    if (open < 0) break;
    const head = css.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < css.length && depth) { if (css[j] === '{') depth++; else if (css[j] === '}') depth--; j++; }
    const body = css.slice(open + 1, j - 1);
    if (/^@(media|supports)/.test(head)) out += `${head} {\n${scope(body)}}\n`;
    else if (head.startsWith('@')) out += `${head} {${body}}\n`;
    else out += `${prefix(head)} {${body}}\n`;
    i = j;
  }
  return out;
}

const parts = SOURCES.map((f) => `/* ---- ${f} ---- */\n` + scope(fs.readFileSync(path.join(DIR, f), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')));
const out = `/* Data studio styles, scoped to ${SCOPE}. Generated by scripts/build-css.js from client/css; edit those. */\n${parts.join('\n')}`;
fs.writeFileSync(path.join(DIR, 'studio.css'), out);
console.log(`client/studio.css: ${(out.length / 1024).toFixed(0)} KB`);
